export const RATIOS: Record<string, number> = Object.fromEntries(
  RAW.trim()
    .split(/[|\n]/)
    .map((s) => s.trim())
    .filter(Boolean)
    .map((entry) => {
      const [ticker, r] = entry.split(" ");
      const [a, b] = r.split(":").map(Number);
      return [ticker, b === undefined ? a : a / b];
    }),
);

